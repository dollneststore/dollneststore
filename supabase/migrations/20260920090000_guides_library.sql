## What makes them different from a baby doll

An ordinary baby doll is moulded and painted by machine, in one piece, to a price. A reborn is finished one at a time, which is why no two are identical and why the weight, the floppiness and the skin tone feel so different when you hold one.

## Who buys them

Collectors, people who love newborn photography, parents and grandparents buying a keepsake gift, and adults who simply find them comforting. They are also used in memory and comfort settings, where holding something of a newborn's weight and warmth helps. They are not toys for very young children — see [ages and safety](/guides/are-reborn-dolls-suitable-for-children).

